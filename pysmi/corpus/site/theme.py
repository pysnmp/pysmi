class Theme(NamedTuple):
    """The page frame and the stylesheet a build renders with."""

    #: The page template, with :py:data:`~pysmi.corpus.site.theme.PLACEHOLDERS`
    #: in it.
    page: str = PAGE

    #: The stylesheet, written once at the site root.
    stylesheet: str = STYLESHEET

    #: What the header calls this corpus.
    corpus: str = "MIB corpus"

    def render(self, **fields: str) -> str:
        """One page, the frame filled in.

        Unknown placeholders survive rather than raising: an overridden
        template with a typo in it should produce a page with ``$oops`` on it,
        which somebody will see, rather than stopping a build 3,000 pages in.
        """
        return string.Template(self.page).safe_substitute(
            {"corpus": self.corpus, **fields}
        )


def load_theme(
    page: "str | None" = None,
    stylesheet: "str | None" = None,
    corpus: "str | None" = None,
) -> Theme:
    """A theme, with either file replaced by one the manifest names.

    Args:
        page: a file holding a replacement page template, or ``None`` for the
            built-in one.
        stylesheet: a file holding a replacement stylesheet, likewise.
        corpus: what the header calls this corpus.

    Returns:
        The theme.

    Raises:
        PySmiError: a named file could not be read. A theme that silently fell
            back to the default would publish a whole site in the wrong skin
            and say nothing.
    """
    return Theme(
        page=_read(page, "page template") if page else PAGE,
        stylesheet=_read(stylesheet, "stylesheet") if stylesheet else STYLESHEET,
        corpus=corpus or "MIB corpus",
    )


def _read(path: str, what: str) -> str:
    """One theme file, or a failure that names it."""
    try:
        with open(path, encoding="utf-8") as fileObj:
            return fileObj.read()

    except OSError as exc:
        raise error.PySmiError(
            f"cannot read the {what} at {os.path.abspath(path)}: {exc}"
        ) from exc
