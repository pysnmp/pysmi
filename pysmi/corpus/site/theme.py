"""The frame every page is written into, and how a distribution replaces it.

A downstream distribution publishes this site beside its own documentation and
wants it to look like the rest of that documentation. Forking the generator to
change a header is the outcome to avoid, so the frame is data: a
:py:class:`Theme` carries the page template and the stylesheet, and a manifest
names files that replace either.

:py:class:`string.Template` rather than a template engine, because PySMI's
runtime dependencies are ``ply`` and ``requests`` and a page frame is not a
reason for a third. ``$name`` substitution is all a frame needs, and
``safe_substitute`` means an unknown placeholder in an overridden template
renders as itself rather than raising in the middle of a 5,500-page build.

See pysnmp/pysmi#276.
"""

import os
import string
from typing import Final, NamedTuple

from pysmi import error

#: The placeholders a page template may use.
#:
#: ``head`` is where the crawl metadata a distribution build asks for goes --
#: see pysnmp/pysmi#284 -- and is empty otherwise.
PLACEHOLDERS: Final[tuple[str, ...]] = (
    "title",
    "head",
    "root",
    "stylesheet",
    "heading",
    "breadcrumb",
    "content",
    "corpus",
    "generator",
)

#: The default page template -- one file, no scripts, nothing fetched. Every
#: fact the page states is in the bytes the server sent, which is what
#: pysnmp/pysmi#284 requires of it.
PAGE: Final = """\
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>$title</title>
<link rel="stylesheet" href="$stylesheet">
$head</head>
<body>
<header class="site">
<a class="home" href="${root}browse/">$corpus</a>
<nav class="breadcrumb">$breadcrumb</nav>
</header>
<main>
<h1>$heading</h1>
$content</main>
<footer class="site">
<p>Generated by $generator.</p>
</footer>
</body>
</html>
"""

